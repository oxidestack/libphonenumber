//! Embeds libphonenumber's serialized metadata (`resources/data/`, `resources/testing/`) and reads the calling-code
//! map out of `CountryCodeToRegionCodeMap.java`, so nothing is read from disk at run time.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

/// The `(file name, path)` of every file in `dir` whose name starts with `prefix`, sorted by name.
fn files(dir: &Path, prefix: &str) -> Vec<(String, PathBuf)> {
    let mut out: Vec<_> = std::fs::read_dir(dir)
        .expect("resources")
        .map(|e| e.expect("entry").path())
        .filter_map(|p| {
            let name = p.file_name()?.to_str()?.to_string();
            name.starts_with(prefix).then_some((name, p))
        })
        .collect();
    out.sort();
    out
}

/// The `put(code, list)` calls of a generated `CountryCodeToRegionCodeMap*.java`, in source order.
fn country_code_map(java: &str) -> Vec<(i32, Vec<String>)> {
    let mut out = Vec::new();
    let mut regions = Vec::new();
    for line in java.lines().map(str::trim) {
        if let Some(rest) = line.strip_prefix("listWithRegionCode.add(\"") {
            regions.push(rest.trim_end_matches("\");").to_string());
        } else if let Some(rest) = line.strip_prefix("countryCodeToRegionCodeMap.put(") {
            let code = rest.split(',').next().expect("code").trim().parse().expect("calling code");
            out.push((code, std::mem::take(&mut regions)));
        }
    }
    out
}

fn emit(src: &mut String, name: &str, dir: &Path, prefix: &str, java: &Path) {
    writeln!(src, "pub(crate) static {name}_FILES: &[(&str, &[u8])] = &[").expect("write");
    for (file, path) in files(dir, prefix) {
        let key = file.rsplit('_').next().expect("suffix");
        writeln!(src, "    ({key:?}, include_bytes!({:?})),", path.to_string_lossy()).expect("write");
    }
    src.push_str("];\n");
    let text = std::fs::read_to_string(java).expect("map source");
    writeln!(src, "pub(crate) static {name}_MAP: &[(i32, &[&str])] = &[").expect("write");
    for (code, regions) in country_code_map(&text) {
        writeln!(src, "    ({code}, &{regions:?}),").expect("write");
    }
    src.push_str("];\n");
}

fn main() {
    let root = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").expect("manifest dir")).join("resources");
    println!("cargo:rerun-if-changed=resources");
    let mut src = String::from("// Generated by build.rs from resources/.\n");
    emit(&mut src, "DEFAULT", &root.join("data"), "PhoneNumberMetadataProto_", &root.join("CountryCodeToRegionCodeMap.java"));
    emit(
        &mut src,
        "TESTING",
        &root.join("testing"),
        "PhoneNumberMetadataProtoForTesting_",
        &root.join("testing/CountryCodeToRegionCodeMapForTesting.java"),
    );
    let out = PathBuf::from(std::env::var("OUT_DIR").expect("out dir")).join("metadata_files.rs");
    std::fs::write(out, src).expect("write metadata_files.rs");
}
